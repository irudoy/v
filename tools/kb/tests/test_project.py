def make_repo(root, files=None):
    defaults = {
        "tools/kb/contracts.toml": CONTRACTS,
        "tools/kb/bench.toml": BENCH,
        "tools/kb/config.toml": CONFIG,
        "tools/kb/projections.toml": PROJECTIONS,
        "tools/defs/build.py": "",
        "defs/source.toml": "",
        "defs/JK08A.xml": "<!-- Generated by tools/defs/build.py -->\n",
        "AGENTS.md": AGENTS,
        "kb/names.csv": "generated by kb sync\n",
    }
    defaults.update(files or {})
    for name, text in defaults.items():
        if text is None:
            continue
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    subprocess.run(["git", "add", "-A", "-f"], cwd=root, check=True)
    return root


class PathTest(unittest.TestCase):
    def test_a_pattern_stays_inside_one_directory(self):
        self.assertTrue(project.matches("defs/*.xml", "defs/JK08A.xml"))
        self.assertFalse(project.matches("defs/*.xml", "defs/old/JK08A.xml"))
        self.assertFalse(project.matches("defs/*.xml", "JK08A.xml"))
        self.assertTrue(project.matches("defs/*.{xml,xdf}", "defs/JK08A.xdf"))
        self.assertTrue(project.matches("defs/{JK00C,1ND0A}.dtc.csv", "defs/1ND0A.dtc.csv"))
        self.assertFalse(project.matches("defs/{JK00C,1ND0A}.dtc.csv", "defs/JK08A.dtc.csv"))
        self.assertEqual(project.hook.expand("a/{b,c}/{d,e}"), ["a/b/d", "a/b/e", "a/c/d", "a/c/e"])
        self.assertEqual(project.split("AGENTS.md#kb"), ("AGENTS.md", "kb"))
        self.assertEqual(project.split("defs/JK08A.xml"), ("defs/JK08A.xml", None))

    def test_a_section_lies_between_its_markers(self):
        text = "a\n<!-- kb:begin -->\nb\n<!-- kb:end -->\nc\n"
        start, stop = project.section_span(text, "kb")
        self.assertEqual(text[start:stop], "\nb\n")
        self.assertIsNone(project.section_span("<!-- kb:end --><!-- kb:begin -->", "kb"))
        self.assertIsNone(project.section_span(text, "other"))


class RepoCase(unittest.TestCase):
    def setUp(self):
        self.scratch = tempfile.TemporaryDirectory()
        self.base = Path(self.scratch.name).resolve()

    def tearDown(self):
        self.scratch.cleanup()

    def repo(self, name, files=None):
        return make_repo(self.base / name, files)


class WriteTest(RepoCase):
    def test_kb_writes_its_sections_and_leaves_the_rest(self):
        root = self.repo("write")
        self.assertEqual(project.write(root), [("AGENTS.md#kb", True)])
        text = (root / "AGENTS.md").read_text()
        self.assertTrue(text.startswith("# Rules\n\n<!-- kb:begin -->\n\n## Knowledge access\n"))
        self.assertTrue(text.endswith("|\n\n<!-- kb:end -->\n"))
        self.assertEqual(project.write(root, ["AGENTS.md#kb"]), [("AGENTS.md#kb", False)])
        with self.assertRaises(KbError) as unknown:
            project.write(root, ["defs/*.xml"])
        self.assertEqual(unknown.exception.code, 2)

    def test_the_check_mode_writes_nothing(self):
        root = self.repo("check")
        before = (root / "AGENTS.md").read_text()
        self.assertEqual(project.write(root, check=True), [("AGENTS.md#kb", True)])
        self.assertEqual((root / "AGENTS.md").read_text(), before)
        project.write(root)
        self.assertEqual(project.write(root, check=True), [("AGENTS.md#kb", False)])

    def test_the_command_exits_with_1_when_a_projection_differs(self):
        root = self.repo("command")
        with contextlib.redirect_stdout(io.StringIO()) as out:
            self.assertEqual(cli.command_project(Namespace(check=True, paths=[]), root), 1)
        self.assertEqual(out.getvalue(), "AGENTS.md#kb: differs from its rendering\n")
        held = []

        @contextlib.contextmanager
        def lock(where):
            held.append(where)
            yield

        with mock.patch.object(cli.lock, "held", lock), \
                contextlib.redirect_stdout(io.StringIO()) as out:
            self.assertEqual(cli.command_project(Namespace(check=False, paths=[]), root), 0)
        self.assertEqual((held, out.getvalue()), ([root], "AGENTS.md#kb: written\n"))
        with contextlib.redirect_stdout(io.StringIO()) as out:
            self.assertEqual(cli.command_project(Namespace(check=True, paths=[]), root), 0)
        self.assertEqual(out.getvalue(), "AGENTS.md#kb: current\n")

    def test_a_section_without_markers_is_an_error(self):
        root = self.repo("markers", {"AGENTS.md": "# Rules\n"})
        with self.assertRaises(KbError):
            project.write(root)

    def test_the_section_states_the_questions_and_owners_of_the_stage(self):
        root = self.repo("agents")
        text = project.agents(root)
        self.assertIn("tools/kb/contracts.toml", text)
        self.assertIn("| What is at an address | `uv run kb at jk00d:ffff1034` |", text)
        self.assertNotIn("Where a meaning is", text)
        self.assertIn("| `roms.csv` | Images | itself |", text)
        self.assertIn("| `l0` exports | Code structure | `l0/<layout>/` |", text)
        self.assertIn("| `kb/names.csv` | Generated names | itself, shrinking with each "
                      "conversion |", text)
        self.assertIn("| `profiles.toml` | Targets | the registry |", text)
        self.assertIn("| `maps.csv` | Map tracker | `build_tracker.py` |", text)
        self.assertIn("| `symbols/7mfk.csv` | Names of 7mfk | the registry |", text)
        self.assertIn("| `symbols/1nd.csv` | Names of 1nd | the registry |", text)
        self.assertTrue(text.startswith("\n\n## Knowledge access\n"))
        self.assertTrue(text.endswith("|\n\n"))


def _interp(root):
    return {"defs/A.interp.csv": "a\n", "defs/B.interp.csv": "b\n"}


class PatternTest(RepoCase):
    """A projection of a pattern whose generator returns {path: text}, at
    stage 3, where it applies."""

    def setUp(self):
        super().setUp()
        original = project.generator
        patcher = mock.patch.object(project, "generator", lambda entry: _interp
                                    if entry["path"] == "defs/*.interp.csv" else original(entry))
        patcher.start()
        self.addCleanup(patcher.stop)

    def repo(self, name, files=None):
        return super().repo(name, {
            "tools/kb/projections.toml": PROJECTIONS + PATTERN,
            "tools/kb/bench.toml": BENCH.replace("stage = 2\n", "stage = 3\n", 1),
            "defs/A.interp.csv": "a\n", "defs/B.interp.csv": "old\n", **(files or {})})

    def test_kb_writes_each_file_of_the_pattern(self):
        root = self.repo("write")
        self.assertIn(("defs/*.interp.csv", True), project.write(root))
        self.assertEqual((root / "defs/B.interp.csv").read_text(), "b\n")
        self.assertIn(("defs/*.interp.csv", False), project.write(root))
        self.assertEqual(project.check(root), [])

    def test_the_check_mode_leaves_the_files_of_the_pattern(self):
        root = self.repo("check")
        self.assertIn(("defs/*.interp.csv", True), project.write(root, check=True))
        self.assertEqual((root / "defs/B.interp.csv").read_text(), "old\n")

    def test_the_check_compares_the_tracked_files_with_the_rendering(self):
        root = self.repo("compare", {"defs/C.interp.csv": "c\n"})
        project.write(root)
        (root / "defs/A.interp.csv").write_text("x\n")
        self.assertEqual(project.check(root), [
            "defs/C.interp.csv: matches defs/*.interp.csv and is no file of its rendering "
            "(fix: git rm defs/C.interp.csv)",
            "defs/A.interp.csv: file: differs from its rendering "
            "(fix: uv run kb project defs/*.interp.csv)"])

    def test_a_rendered_file_that_git_does_not_track_fails(self):
        root = self.repo("untracked", {"defs/B.interp.csv": None})
        project.write(root)
        self.assertEqual(project.check(root), [
            "defs/B.interp.csv: not tracked (fix: git add defs/B.interp.csv)"])

    def test_a_registry_of_the_stage_changes_owner_when_kb_renders_its_files(self):
        root = self.repo("owner")
        text = project.agents(root)
        self.assertIn("| `defs/*.interp.csv` | Interpolation | `fn` meanings |",
                      text)
        self.assertIn("| `profiles.toml` | Targets | the registry |", text)
        self.assertIn("| `l0` exports | Code structure | `l0/<layout>/` |", text)
        owners = project.owners(root)
        self.assertEqual(owners["pending"], {3: 1, 5: 1, 9: 1})
        self.assertEqual([row["registry"] for row in owners["converted"]],
                         ["l0 exports", "kb/names.csv", "defs/*.interp.csv"])

    def test_a_projection_ahead_of_the_stage_leaves_the_owner(self):
        root = self.repo("ahead", {"tools/kb/bench.toml": BENCH})
        self.assertIn("| `defs/*.interp.csv` | Interpolation | the registry |",
                      project.agents(root))

    def test_a_module_that_reads_kb_changes_owner_once_no_adapter_reads_it(self):
        row = '  ["Tables of `patches/runtime.py`", "Hook keys", "3", "Feature targets", "The module reads them through the `kb` API"],\n'
        spec = CONTRACTS.replace('  ["`symbols/7mfk.csv`"', row + '  ["`symbols/7mfk.csv`"')

        def owner(name, text, read):
            root = self.repo(name, {"tools/kb/contracts.toml": spec, "patches/runtime.py": text})
            adapter = SimpleNamespace(inputs=lambda root: read)
            with mock.patch.object(project.adapters, "ORDER", (adapter,)):
                return project.agents(root)

        converted = "| Tables of `patches/runtime.py` | Hook keys | Feature targets |"
        pending = "| Tables of `patches/runtime.py` | Hook keys | the registry |"
        self.assertIn(converted, owner("reader", "from kb import targets\n", []))
        self.assertIn(pending, owner("read", "import kb.targets\n", ["patches/runtime.py"]))
        self.assertIn(pending, owner("tables", "KEYS = {'a': 1}\n", []))

    def test_the_list_names_no_registry_that_its_files_convert(self):
        bench = BENCH.replace('stage = 2\nconverted = ["l0 exports"]',
                              'stage = 3\nconverted = ["l0 exports", "defs/*.interp.csv"]')
        root = self.repo("files", {"tools/kb/bench.toml": bench})
        project.write(root)
        self.assertEqual(project.check(root), [
            "tools/kb/bench.toml: converted defs/*.interp.csv: its files convert it "
            "(fix: edit tools/kb/bench.toml)"])


class CheckTest(RepoCase):
    def test_rendered_projections_pass(self):
        root = self.repo("pass")
        self.assertEqual(project.check(root), [
            "AGENTS.md: kb: differs from its rendering (fix: uv run kb project AGENTS.md#kb)"])
        project.write(root)
        self.assertEqual(project.check(root), [])

    def test_a_generated_file_without_a_projection_fails(self):
        root = self.repo("unregistered", {"tools/defs/table.csv": "# Do not edit\n"})
        project.write(root)
        self.assertEqual(project.check(root), [
            "tools/defs/table.csv: declares itself generated and no projection registers it "
            "(fix: edit tools/kb/projections.toml)"])

    def test_entries_name_existing_paths_and_known_keys(self):
        entries = PROJECTIONS + """
[[projection]]
path = "defs/*.xdf"
generator = "tools/defs/missing.py"
inputs = ["defs/missing.toml"]
consumers = []
read = "hidden"

[[projection]]
path = "defs/JK08A.xml"
generator = "tools/defs/build.py"
inputs = []
consumers = []
read = "open"
owner = "x"
"""
        root = self.repo("entries", {"tools/kb/projections.toml": entries})
        project.write(root)
        where = "tools/kb/projections.toml: projection"
        fix = "(fix: edit tools/kb/projections.toml)"
        self.assertEqual(project.check(root), [
            f"{where} defs/*.xdf: read 'hidden' is none of guarded, open {fix}",
            f"{where} defs/*.xdf: path matches no tracked file {fix}",
            f"{where} defs/*.xdf: inputs defs/missing.toml does not exist {fix}",
            f"{where} defs/*.xdf: generator names tools/defs/missing.py, which does not exist "
            f"{fix}",
            f"{where} defs/JK08A.xml: keys ['owner'] unknown, [] missing {fix}",
        ])

    def test_a_file_belongs_to_one_projection(self):
        entries = PROJECTIONS + """
[[projection]]
path = "defs/JK08A.xml"
generator = "tools/defs/build.py"
inputs = []
consumers = []
read = "open"
"""
        root = self.repo("twice", {"tools/kb/projections.toml": entries})
        project.write(root)
        self.assertEqual(project.check(root), [
            "tools/kb/projections.toml: projection defs/JK08A.xml: defs/JK08A.xml is also a "
            "file of projection defs/*.xml (fix: edit tools/kb/projections.toml)"])


