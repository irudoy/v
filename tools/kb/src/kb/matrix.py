"""The feature section of `rom-images/support-matrix.md` (tools/kb/SPEC.md,
sections 7.9 and 14).

`features` renders the section `features` of the matrix from the model. Its
first table has a row for each layout with the images that share its
addresses and a column for each feature in the order of the build: the
runtime, the features that redirect ROM words in the order in which the
build applies them, and the others by slug. A cell states the status of the
target of the feature on the layout and what the model derives from the
target: the ROM and RAM of the runtime, the switched map families and those
that the layout does not support, the telemetry mailbox, the `ecu_ram` fields
whose source the layout lacks, and the other meanings that the target
requires without a symbol there, each by the state of its status. The second
table gives the title, summary, and specifications of each feature, and a
specification that names no file refuses the rendering. The facts live in the
feature files of `kb/`; the section only shows them.
"""

from collections import Counter, defaultdict
import os
from pathlib import Path

from kb import repo
from kb.adapters import layouts as build
from kb.repo import KbError

PATH = Path("rom-images/support-matrix.md")
SECTION = "features"
RUNTIME = "runtime"
# The spans of the runtime allocation: the prefix of their keys and the label.
SPANS = (("injected_rom", "ROM"), ("injected_ram", "RAM"))
# The states of a meaning without a symbol, in the order of a cell; a meaning
# without a status is unknown.
STATES = ("absent", "unresolved", "unknown")


def features(root=repo.ROOT):
    """The text of the section from the model of the repository."""
    from kb import compile
    return render(compile.cached(root), root)


def order(model):
    """The feature slugs of the model in the order of the build."""
    slugs = sorted({feature for feature, _ in model.targets}
                   | {slug for kind, slug in model.entities if kind == "feature"})
    slugs = [slug for slug in slugs if not (
        model.entities.get(('feature', slug))
        and model.entities['feature', slug].props.get('catalog'))]
    first = (RUNTIME, *build.FEATURES)
    return [slug for slug in first if slug in slugs] + [slug for slug in slugs
                                                        if slug not in first]


def render(model, root=repo.ROOT):
    slugs = order(model)
    entities = {slug: model.entities.get(("feature", slug)) for slug in slugs}
    props = {slug: entity.props if entity is not None else {}
             for slug, entity in entities.items()}
    titles = [props[slug].get("title") or slug for slug in slugs]
    gaps = missing(model)
    lines = [
        "",
        "",
        "## Feature targets",
        "",
        f"Generated by `uv run kb project {PATH.as_posix()}#{SECTION}` from the",
        "feature files of `kb/`. A row is a layout with the images that share its",
        "addresses, and a cell states the status of the feature target on the layout",
        "with what the model derives from it: the ROM and RAM of the runtime, the",
        "switched map families and those that the layout does not support, the",
        "telemetry mailbox and the fields whose source the layout lacks, and the other",
        "required meanings without a symbol there, each by the state of its status.",
        "`uv run kb gaps --feature <feature> --layout <layout>` lists the meanings.",
        "",
        "| Layout | Images | " + " | ".join(titles) + " |",
        "| --- | --- | " + " | ".join("---" for _ in slugs) + " |",
    ]
    for layout in model.layouts.values():
        cells = [cell(model, slug, layout.id, gaps) for slug in slugs]
        lines.append(f"| `{layout.id}` | {', '.join(layout.images)} | "
                     + " | ".join(cells) + " |")
    lines.extend(["", "| Feature | Summary | Specifications |", "| --- | --- | --- |"])
    for slug, title in zip(slugs, titles):
        links = ", ".join(_link(root, slug, path) for path in props[slug].get("specs", ()))
        summary = _escaped(" ".join(str(props[slug].get("summary", "")).split()))
        lines.append(f"| {_escaped(title)} (`{slug}`) | {summary} | {links} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def cell(model, feature, layout, gaps):
    """The status of the target of a feature on a layout and its numbers."""
    target = model.targets.get((feature, layout))
    if target is None:
        return "no target"
    props, parts = target.props, []
    spans = [f"{label} `{_span(props, key)}`" for key, label in SPANS
             if f"{key}_start" in props]
    if spans:
        parts.append(", ".join(spans))
    if "families" in props:
        count = len(props["families"])
        text = f"{count} switched {'family' if count == 1 else 'families'}"
        unsupported = len(props.get("unsupported", ()))
        parts.append(text + (f", {unsupported} unsupported" if unsupported else ""))
    if "mailbox_index" in props:
        parts.append(f"mailbox {props['mailbox_index']}")
    fields = unavailable(model, target)
    if fields is not None:
        count = sum(fields.values())
        parts.append(f"{_counted(count, 'field', 'fields')} unavailable{_states(fields)}"
                     if count else "every field available")
    meanings = gaps.get((feature, layout))
    if meanings:
        count = sum(meanings.values())
        parts.append(f"{_counted(count, 'meaning', 'meanings')} without a symbol"
                     f"{_states(meanings)}")
    return "; ".join([target.status or "no status", *parts])


def unavailable(model, target):
    """Counter({state: count}) of the `ecu_ram` fields of the feature of a
    target that the layout of the target lacks: no role of the target fills
    the field and its source meaning has no symbol there; None for a feature
    that requires no such field."""
    entity = model.entities.get(("feature", target.feature))
    found, sources = Counter(), 0
    roles = target.props.get("roles", {})
    for ref in entity.refs.get("requires", ()) if entity is not None else ():
        field = model.entities.get(ref) if isinstance(ref, tuple) else None
        keys = list(field.refs.get("source", ())) if field is not None else []
        meaning = model.meaning_of(keys[0]) if len(keys) == 1 else None
        if meaning is None:
            continue
        sources += 1
        if ref[1] in roles or target.layout in meaning.symbols:
            continue
        status = meaning.statuses.get(target.layout)
        found[status.state if status is not None else "unknown"] += 1
    return found if sources else None


def missing(model):
    """{(feature, layout): Counter({state: count})} of the meanings that a
    feature or its target requires directly on a layout where they have no
    symbol."""
    meanings = {meaning.key: meaning for meaning in model.meanings if meaning.name}
    found = defaultdict(Counter)
    for (key, layout), requirements in model.required().items():
        status = meanings[key].statuses.get(layout)
        for requirement in requirements:
            if requirement != "family" and " via " not in requirement:
                found[(requirement, layout)][status.state if status is not None
                                             else "unknown"] += 1
    return dict(found)


def _span(props, key):
    start, end = (int(props[f"{key}_{edge}"], 16) for edge in ("start", "end"))
    return f"0x{start:X}..0x{end:X}"


def _states(counts):
    return " (" + ", ".join(f"{counts[state]} {state}" for state in STATES
                            if counts[state]) + ")"


def _counted(count, one, many):
    return f"{count} {one if count == 1 else many}"


def _link(root, slug, path):
    if not (root / path).is_file():
        raise KbError(f"{slug}/feature: specs names no file {path}", code=3)
    return f"[`{path}`]({Path(os.path.relpath(root / path, root / PATH.parent)).as_posix()})"


def _escaped(text):
    return str(text).replace("|", "\\|")
