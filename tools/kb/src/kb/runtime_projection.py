"""Generate the numeric runtime bindings consumed by the patch builder."""

import json

from kb import repo, store, targets


FEATURES = ("map_switching", "rolling_launch", "can_telemetry")
IGNITION_TEMPLATE_LAYOUT = "1nd"


def document(root=repo.ROOT):
    """Project runtime inputs without importing a patch consumer."""
    runtime = store.load(root, store.path_of("feature", "runtime"))
    layouts = sorted({entry["layout"] for entry in runtime.get("target", ())})
    found = {
        "schema_version": 1,
        "canonical_layout": targets.CANONICAL,
        "images": {image: layout.id for layout in repo.layouts(root).values()
                   if layout.id in layouts for image in layout.images},
        "canonical_symbols": {feature: targets.canonical_symbols(feature, root)
                              for feature in FEATURES},
        "map_hook_keys": {
            layout: {f"{address:08x}": key for address, key in sorted(
                targets.hook_keys("map_switching", layout, root).items())}
            for layout in layouts
        },
        "ignition_state_template": {},
        "layouts": {},
    }
    template = targets.target("map_switching", IGNITION_TEMPLATE_LAYOUT, root)
    delta = targets.target("runtime", IGNITION_TEMPLATE_LAYOUT, root)["rom_delta"]
    storage = template["ignition_state_storage"]
    for key in sorted(set(template["families"]) & set(storage)):
        found["ignition_state_template"][key] = [
            targets.address(template["families"][key], IGNITION_TEMPLATE_LAYOUT, root),
            int(storage[key]["pointer_table"], 16) - delta,
        ]
    for layout in layouts:
        fuel = targets.meaning("rolling_launch", layout, "fuel_inhibit", root)
        rolling = targets.target("rolling_launch", layout, root)
        row = {
            "ascd_main_bit": targets.bit("ascd_state/ram", layout, "main", root),
            "fuel_cut_active_bit": targets.bit(fuel, layout, "active", root),
            "fuel_cut_address": targets.address(fuel, layout, root),
            "knock_surface_bit": targets.bit(
                "knock_surface_state/ram", layout, "high_detonation", root),
            "knock_surface_address": targets.address("knock_surface_state/ram", layout, root),
        }
        if layout == targets.CANONICAL or "fuel_inhibit_mask" in rolling.get("symbols", {}):
            row["fuel_inhibit_mask"] = targets.address("fuel_inhibit_mask/ram", layout, root)
        found["layouts"][layout] = row
    return found


def _value(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "[" + ", ".join(_value(item) for item in value) + "]"
    if type(value) is int:
        return f"0x{value:X}" if value >= 0 else str(value)
    raise TypeError(f"unsupported runtime binding value: {value!r}")


def render(root=repo.ROOT):
    """Return the deterministic TOML projection of current KB owners."""
    lines = ["# Generated by kb.runtime_projection:render. Edit the KB owners."]

    def table(values, path=()):
        if path:
            lines.extend(("", "[" + ".".join(_value(key) for key in path) + "]"))
        for key, value in values.items():
            if not isinstance(value, dict):
                lines.append(f"{_value(key)} = {_value(value)}")
        for key, value in values.items():
            if isinstance(value, dict):
                table(value, (*path, key))

    table(document(root))
    return "\n".join(lines) + "\n"
