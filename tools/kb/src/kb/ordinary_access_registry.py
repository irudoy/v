"""Registration of existing ordinary-link access proofs and their shared routes."""

from dataclasses import dataclass
from importlib import import_module


@dataclass(frozen=True)
class Family:
    mode: str
    contract_name: str
    evidence_name: str
    resolution_name: str
    captures: tuple
    sources: tuple
    direct_owning: bool = True
    owner_fallback: bool = False
    withdrawal_only: bool = False

    @property
    def contract(self):
        return import_module('kb.'+self.contract_name)

    @property
    def evidence(self):
        return import_module('kb.'+self.evidence_name)

    @property
    def resolution(self):
        return import_module('kb.'+self.resolution_name)

    @property
    def source_files(self):
        return (*(f'tools/kb/src/kb/{name}.py' for name in
            (self.contract_name,self.evidence_name,self.resolution_name)),
            *(f'tools/sh-elf-run/{producer}.py' for component,producer in self.captures),*self.sources)


