def families():
    """Refuse malformed or duplicate authoritative registration before routing."""
    if not FAMILIES or any(type(family) is not Family for family in FAMILIES):
        raise ValueError('ordinary access registration requires explicit family records')
    for field in ('mode','contract_name','evidence_name','resolution_name'):
        values=[getattr(family,field) for family in FAMILIES]
        if any(type(value) is not str or not value for value in values) or len(set(values))!=len(values):
            raise ValueError('ordinary access registration repeats or omits '+field)
    bindings=[binding for family in FAMILIES for binding in family.captures]
    if any(not family.sources or not family.captures or type(family.direct_owning) is not bool
            or type(family.owner_fallback) is not bool or type(family.withdrawal_only) is not bool
            or family.withdrawal_only and (family.direct_owning or family.owner_fallback) for family in FAMILIES):
        raise ValueError('ordinary access registration lacks sources, capture or explicit owning policy')
    if any(type(binding) is not tuple or len(binding)!=2 or any(type(part) is not str or not part for part in binding)
            for binding in bindings):
        raise ValueError('ordinary access registration changes a complete capture binding')
    if any(len({binding[index] for binding in bindings})!=len(bindings) for index in (0,1)):
        raise ValueError('ordinary access registration repeats a capture or producer')
    if tuple(family.mode for family in FAMILIES)!=MODES:
        raise ValueError('ordinary access registration and derived mode coverage differ')
    return FAMILIES


def require_bindings():
    """Check route coverage without interpreting or qualifying any domain result."""
    prefixes=set();descriptors=set()
    for family in families():
        contract,evidence,resolution=family.contract,family.evidence,family.resolution
        if (contract.PREFIX in prefixes or contract.DESCRIPTOR in descriptors
                or contract.DESCRIPTOR not in family.sources
                or not contract.registered(dict(mode=family.mode))
                or any(path not in EXECUTION_FILES for path in family.source_files)):
            raise ValueError('ordinary access registration repeats or omits an exact namespace source')
        prefixes.add(contract.PREFIX);descriptors.add(contract.DESCRIPTOR)
        for module,names in ((contract,('registered','looks_like_access','publication','operations')),
                (evidence,('failure','accepted','link_failure','identity_only','dependency_state','require_primary')),
                (resolution,('require_transition','publication_expected','retires'))):
            if any(not callable(getattr(module,name,None)) for name in names):
                raise ValueError('ordinary access registration lacks a mandatory existing consumer hook')
        components=getattr(evidence,'COMPONENTS',{})
        if set(components)!={component for component,producer in family.captures}:
            raise ValueError('ordinary access registration and independent consumer coverage differ')
        if any(not callable(getattr(consumer,'require_primary',None)) for consumer in components.values()):
            raise ValueError('ordinary access registration lacks an independent raw consumer')
    return families()


def matching(item):
    return tuple(family for family in families() if family.contract.registered(item))


def registered(item):
    return bool(matching(item))


def link_families(link):
    return tuple(family for family in families() if family.contract.looks_like_access(link))


def identity_only(symbol):
    return any(family.evidence.identity_only(symbol) for family in families() if not family.withdrawal_only)


def publication(link,item):
    return any(family.contract.publication(link,item) for family in families() if not family.withdrawal_only)


def active(model,entries):
    return tuple(family for family in families() if any(family.contract.registered(item) for item in entries)
        or any(family.contract.looks_like_access(link) for link in model.links))


def claim_family(symbol,claim):
    matches=tuple(family for family in families()
        if any(family.contract.registered(item) for item in claim['evidence']))
    if matches:
        if len(matches)!=1:raise ValueError('ambiguous reserved ordinary access claim')
        return matches[0]
    return next((family for family in families() if family.owner_fallback and symbol.meaning is not None
        and symbol.meaning.key in {row[2] for row in family.contract.IDENTITIES}),None)


def original_family(claim):
    for family in families():
        contract=family.contract
        if (family.owner_fallback and claim['owner'] in {row[2] for row in contract.IDENTITIES}
                or any(claim['owner']==row[2] and contract.digest(contract.plain(claim))==row[10]
                    for row in contract.IDENTITIES)):
            return family
    return None


def operation_families(ops,root):
    """Keep exact complete batch checks in each existing ordinary contract."""
    return tuple(family for family in families() if family.contract.operations(ops,root))


def removals(selected,root):
    result=[]
    for family in selected:
        contract=family.contract
        if callable(getattr(contract,'removal',None)):
            result.extend(contract.removal(row) for row in contract.descriptor(root)['reference']
                if contract.correction(row))
    return result


def captures():
    return tuple(binding for family in families() for binding in family.captures)


def require_captures(witness):
    """Require complete capture presence without granting domain admission."""
    if type(witness) is not dict or any(type(witness.get(component)) is not dict or not witness[component]
            for component,producer in captures()):
        raise ValueError('the complete original omits a registered ordinary access capture')
