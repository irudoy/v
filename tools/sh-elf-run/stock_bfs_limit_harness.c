static volatile uint8_t *ram(uint32_t address)
{
    return (volatile uint8_t *)(uintptr_t)(TEST_RAM_BASE + (address & 0xffffU));
}

static void set_word(uint32_t address, uint16_t value)
{
    *(volatile uint16_t *)ram(address) = value;
}

static int fail(const char *name, const char *field, uint32_t actual, uint32_t expected)
{
    printf("VQ_SH_ELF_STOCK_CODE status=FAIL case=%s field=%s actual=%08lx expected=%08lx\n",
           name, field, (unsigned long)actual, (unsigned long)expected);
    return 0;
}

static void set_pattern(uint8_t pattern)
{
    size_t index;
    for (index=0; index<16; ++index)
        *(volatile uint8_t *)(uintptr_t)(LIMIT_TABLE+index) = patterns[pattern][index];
}

static int preserved_tables(const char *name, uint8_t pattern)
{
    size_t index;
    for (index=0; index<16; ++index) {
        if (*(const volatile uint8_t *)(uintptr_t)(LIMIT_TABLE+index) != patterns[pattern][index])
            return fail(name,"read-only-limit-curve",index,0);
        if (word_cells[index] != index*4096U)
            return fail(name,"read-only-explicit-word-context",index,0);
    }
    for (index=0; index<12; ++index)
        if (*(const volatile uint8_t *)(uintptr_t)(ALTERNATE_TABLE+index) != alternate[index])
            return fail(name,"read-only-alternate-grid",index,0);
    return 1;
}

static void prepare(const struct limit_case *test)
{
    size_t w, byte;
    for (w=0; w<ARRAY_SIZE(windows); ++w)
        for (byte=0; byte<windows[w].size; ++byte)
            ram(windows[w].start)[byte] = (uint8_t)(29U*byte+31U*w+7U);
    set_word(WORKING,test->working);
    set_word(BLENDED,test->blended);
    set_word(CORRECTION,(uint16_t)test->correction);
    set_word(OUTPUT,0xa55a);
    ram(FLAGS)[0] = test->flags;
    ram(RPM_BYTE)[0] = test->rpm;
    ram(SPEED_BYTE)[0] = test->speed;
    ram(THROTTLE_BYTE)[0] = test->throttle;
    ram(CAP_BYTE)[0] = 0xa5;
    set_pattern(test->pattern);
    for (w=0; w<ARRAY_SIZE(windows); ++w)
        for (byte=0; byte<windows[w].size; ++byte)
            windows[w].before[byte] = ram(windows[w].start)[byte];
}

static int run_limit(const struct limit_case *test)
{
    uint32_t state[3], result;
    const uint32_t context[] = {
        test->blend,test->correction,(uint32_t)(uintptr_t)ram(PRIMARY_BASE),0x12345678U,
    };
    size_t w, byte;
    prepare(test);
    result = stock_invoke_bfs_limit(SELECTOR_ENTRY,context,state);
    if (result != test->output || *(const volatile uint16_t *)ram(OUTPUT) != test->output)
        return fail(test->name,"returned-or-published-bfs-word",result,test->output);
    if (ram(CAP_BYTE)[0] != test->cap)
        return fail(test->name,"normal-cap-or-diagnostic-preservation",ram(CAP_BYTE)[0],test->cap);
    if (state[0] != 0x12345678U || state[1] != (uint32_t)(uintptr_t)ram(PRIMARY_BASE)
        || state[2]+2U != (uint32_t)(uintptr_t)ram(OUTPUT))
        return fail(test->name,"macl-gbr-or-publication-base",state[0],0x12345678U);
    for (w=0; w<ARRAY_SIZE(windows); ++w)
        for (byte=0; byte<windows[w].size; ++byte) {
            uint32_t address=windows[w].start+(uint32_t)byte;
            if (address == CAP_BYTE || (address>=OUTPUT && address-OUTPUT<2U)) continue;
            if (ram(address)[0] != windows[w].before[byte])
                return fail(test->name,"read-only-source-mode-correction-or-neighbor",address,0);
        }
    return preserved_tables(test->name,test->pattern);
}

static int run_wrapper(const struct wrapper_case *test)
{
    uint32_t result;
    set_pattern(test->pattern);
    result=stock_invoke_curve(WRAPPER_ENTRY,LIMIT_TABLE,test->coordinate);
    if (result != test->output)
        return fail(test->name,"natural-wrapper-return",result,test->output);
    return preserved_tables(test->name,test->pattern);
}

static int run_word(const struct word_case *test)
{
    uint32_t result=stock_invoke_format_curve(BODY_ENTRY,0x100U,
                                            (uint32_t)(uintptr_t)word_cells,test->coordinate);
    if (result != test->output)
        return fail(test->name,"explicit-shared-word-context",result,test->output);
    return preserved_tables(test->name,wrapper_cases[ARRAY_SIZE(wrapper_cases)-1].pattern);
}

int main(void)
{
    size_t index, cases=0;
    for (index=0; index<ARRAY_SIZE(limit_cases); ++index) {
        if (!run_limit(limit_cases+index)) return 1;
        ++cases;
    }
    for (index=0; index<ARRAY_SIZE(wrapper_cases); ++index) {
        if (!run_wrapper(wrapper_cases+index)) return 1;
        ++cases;
    }
    for (index=0; index<ARRAY_SIZE(word_cases); ++index) {
        if (!run_word(word_cases+index)) return 1;
        ++cases;
    }
    set_pattern(0);
    printf("VQ_SH_ELF_STOCK_CODE status=PASS region=%s cases=%lu\n",REGION_KEY,(unsigned long)cases);
    return 0;
}
