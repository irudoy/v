#!/usr/bin/env python3
"""Generate and check the hash-locked dependency sets of the dashboard packages.

Each target resolves its declared requirement file for one platform and the
project Python into a lock that pins every distribution with its hashes. The
installers and the macOS build install a lock with `--require-hashes` and
`--no-deps`, so they resolve nothing beyond it. `uptime`, which the `pcan`
extra of python-can requires, is published only as a source distribution;
the bootstrap distributions of a target are installed first, so the pinned
setuptools builds it without build isolation.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.version_index import python_version

WRITE_COMMAND = "python tools/can_dashboard/package_locks.py --write"


@dataclass(frozen=True)
class LockTarget:
    name: str
    requirements: str
    lock: str
    platform: str
    bootstrap: tuple[str, ...]


TARGETS = (
    LockTarget(
        "windows",
        "tools/can_dashboard/requirements-windows.txt",
        "tools/can_dashboard/requirements-windows.lock",
        "x86_64-pc-windows-msvc",
        ("pip", "setuptools"),
    ),
    LockTarget(
        "macos",
        "tools/can_dashboard/requirements-macos.txt",
        "tools/can_dashboard/requirements-macos.lock",
        "aarch64-apple-darwin",
        (),
    ),
    LockTarget(
        "macos-build",
        "tools/can_dashboard/requirements-macos-build.txt",
        "tools/can_dashboard/requirements-macos-build.lock",
        "aarch64-apple-darwin",
        ("setuptools",),
    ),
)
TARGET_BY_NAME = {target.name: target for target in TARGETS}

_PIN_RE = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==(?P<version>[^\s;]+)$"
)
_HASH_RE = re.compile(r"^--hash=sha256:[0-9a-f]{64}$")
_COMMENT_RE = re.compile(r"(?:^|\s)#.*$")


@dataclass(frozen=True)
class LockEntry:
    name: str
    version: str
    hashes: tuple[str, ...]
    text: str


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _logical_lines(text: str):
    """Yield requirement lines with continuations joined and comments dropped."""
    pending = []
    for raw in text.splitlines():
        line = _COMMENT_RE.sub("", raw).strip()
        continued = line.endswith("\\")
        if continued:
            line = line[:-1].strip()
        if line:
            pending.append(line)
        if not continued and pending:
            yield " ".join(pending)
            pending = []
    if pending:
        yield " ".join(pending)


def declared_pins(text: str) -> dict[str, str]:
    """Return the `name==version` pins of a requirement file by normalized name."""
    pins = {}
    for line in _logical_lines(text):
        match = _PIN_RE.match(line)
        if match is None:
            raise ValueError(f"requirement is not an exact pin: {line!r}")
        name = normalize(match["name"])
        if name in pins:
            raise ValueError(f"requirement {name} is declared twice")
        pins[name] = match["version"]
    return pins


def parse_lock(text: str) -> dict[str, LockEntry]:
    """Return the entries of a lock by normalized name."""
    entries = {}
    for line in _logical_lines(text):
        requirement, *options = line.split()
        match = _PIN_RE.match(requirement)
        if match is None:
            raise ValueError(f"lock entry is not an exact pin: {requirement!r}")
        if not options or not all(_HASH_RE.match(option) for option in options):
            raise ValueError(f"lock entry {requirement} lacks sha256 hashes")
        name = normalize(match["name"])
        if name in entries:
            raise ValueError(f"lock entry {name} appears twice")
        hashes = tuple(option.removeprefix("--hash=") for option in options)
        entries[name] = LockEntry(
            name,
            match["version"],
            hashes,
            " \\\n    ".join((requirement, *options)) + "\n",
        )
    return entries


def header(target: LockTarget, requirements_text: str, python: str) -> str:
    digest = hashlib.sha256(requirements_text.encode("utf-8")).hexdigest()
    return (
        f"# Generated by `{WRITE_COMMAND}`; do not edit.\n"
        f"# target={target.name} platform={target.platform} python={python}\n"
        f"# requirements={target.requirements} sha256={digest}\n"
    )


def check_lock(
    target: LockTarget, requirements_text: str, lock_text: str, python: str
) -> list[str]:
    """Return the problems of a lock against its declared requirements."""
    expected = header(target, requirements_text, python)
    if not lock_text.startswith(expected):
        return [
            f"{target.lock} was not generated for the current "
            f"{target.requirements}, platform {target.platform}, and "
            f"Python {python}; run {WRITE_COMMAND}"
        ]
    try:
        pins = declared_pins(requirements_text)
        entries = parse_lock(lock_text)
    except ValueError as error:
        return [f"{target.lock}: {error}"]
    problems = []
    for name, version in pins.items():
        entry = entries.get(name)
        if entry is None:
            problems.append(f"{target.lock} does not lock {name}")
        elif entry.version != version:
            problems.append(
                f"{target.lock} locks {name} {entry.version}, "
                f"{target.requirements} declares {version}"
            )
    for name in target.bootstrap:
        if name not in pins:
            problems.append(
                f"{target.requirements} does not declare bootstrap {name}"
            )
    return problems


def bootstrap_text(target: LockTarget, lock_text: str) -> str:
    """Return the lock entries that a target installs before the lock."""
    entries = parse_lock(lock_text)
    return "".join(entries[normalize(name)].text for name in target.bootstrap)


def _read(relative: str) -> str:
    return (ROOT / relative).read_text(encoding="utf-8")


def compile_command(target: LockTarget, python: str) -> list[str]:
    return [
        "uv",
        "pip",
        "compile",
        "--no-config",
        "--quiet",
        "--no-header",
        "--generate-hashes",
        "--python-version",
        python,
        "--python-platform",
        target.platform,
        target.requirements,
    ]


def write_lock(target: LockTarget, python: str) -> None:
    resolved = subprocess.run(
        compile_command(target, python),
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    requirements_text = _read(target.requirements)
    (ROOT / target.lock).write_text(
        header(target, requirements_text, python) + resolved,
        encoding="utf-8",
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--write",
        action="store_true",
        help="resolve every target from the package index and rewrite its lock",
    )
    mode.add_argument(
        "--bootstrap",
        choices=sorted(TARGET_BY_NAME),
        help="print the bootstrap entries of a target lock",
    )
    args = parser.parse_args(argv)
    python = python_version()
    if args.write:
        for target in TARGETS:
            write_lock(target, python)
            print(f"wrote {target.lock}")
        return 0
    target = TARGET_BY_NAME[args.bootstrap]
    sys.stdout.write(bootstrap_text(target, _read(target.lock)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
