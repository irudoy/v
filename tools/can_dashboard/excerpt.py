"""Excerpts of a replay file: the records of a time region, in its format.

An excerpt keeps the format of its source, so the replay, the converters, and
the vendor tools read it as they read the source, and its replay time starts
at zero where its first record lies:

* a PEAK TRC 1.1 trace keeps every record of the region, numbered again from
  1, with the time offsets reduced by the offset of the first kept record and
  `$STARTTIME` and the `Start time` comment moved forward by the same amount;
* a candump log keeps the lines of the region unchanged, because the replay
  counts candump time from the first line;
* a dashboard MLG recording keeps the data blocks of the region with the
  `Elapsed` channel and the block timestamps reduced by the elapsed time of
  the first kept snapshot, and the header start moved forward by the whole
  seconds of that time. The `Date` channel keeps the recorded wall-clock
  second, a hold-last bridge record is kept only behind a kept snapshot, and
  marker blocks are not copied.

The region selects records by the replay time the loader assigns, so an
excerpt holds the items that the replay plays between the two points.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
from decimal import Decimal, InvalidOperation
import math
import os
from pathlib import Path
import re
import struct
import tempfile

from tools.logs import can_telemetry, mlvlg, peak_trc_audit


OLE_AUTOMATION_EPOCH = datetime(1899, 12, 30)
MS_PER_DAY = Decimal(86_400_000)
# PCAN-View writes $STARTTIME with ten decimals, about 9 us.
START_DAYS_DECIMALS = 10
TRC_RECORD = re.compile(
    r"^(?P<number>\s*\d+)\)(?P<offset>\s+\d+(?:\.\d+)?)(?P<rest>\s.*)$",
    re.DOTALL,
)
TRC_START_DAYS = re.compile(
    r"^(?P<prefix>;\$STARTTIME=)(?P<value>[^\r\n]*?)(?P<end>\s*)$",
    re.DOTALL,
)
TRC_START_TEXT = re.compile(
    r"^(?P<prefix>;\s*Start time:\s*)(?P<value>.*?)(?P<end>\s*)$",
    re.DOTALL,
)
TRC_GENERATOR = re.compile(r"^;\s*Generated by\s")
MLG_HEADER = struct.Struct(">6sHIIIHH")
MLG_TIMESTAMP_OFFSET = 8
TIME_FIELDS = ("Date", "Elapsed")


class ExcerptError(ValueError):
    """Raised when an excerpt cannot be written."""


@dataclass(frozen=True)
class Excerpt:
    """A written excerpt: its path, record count, and replay duration."""

    output: Path
    records: int
    duration: float


def default_name(path, start, stop):
    """File name of an excerpt: the source stem and the region in seconds."""
    path = Path(path)
    return f"{path.stem}_{start:.1f}-{stop:.1f}s{path.suffix}"


def _reader_kind(path):
    suffix = Path(path).suffix.lower()
    return {".trc": "TRC", ".mlg": "MLG"}.get(suffix, "candump")


def _trace_start_text(days):
    """PCAN-View text of an OLE Automation date, to 100 us."""
    ticks = int((days * MS_PER_DAY * 10).to_integral_value())
    moment = OLE_AUTOMATION_EPOCH + timedelta(microseconds=ticks * 100)
    return (
        f"{moment:%d.%m.%Y %H:%M:%S}."
        f"{moment.microsecond // 1000:03d}.{moment.microsecond % 1000 // 100}"
    )


def _shift_trace_header(lines, shift_ms, note):
    """Move the trace start forward by shift_ms and add the source note."""
    days = None
    for line in lines:
        match = TRC_START_DAYS.match(line)
        if match is not None:
            try:
                days = Decimal(match["value"].strip())
            except InvalidOperation:
                days = None
            break
    ending = "\r\n" if lines and lines[0].endswith("\r\n") else "\n"
    shifted = []
    position = len(lines)
    for line in lines:
        start_days = TRC_START_DAYS.match(line)
        start_text = TRC_START_TEXT.match(line)
        if days is not None and start_days is not None:
            exponent = days.as_tuple().exponent
            decimals = max(-exponent, START_DAYS_DECIMALS)
            moved = days + shift_ms / MS_PER_DAY
            line = f"{start_days['prefix']}{moved:.{decimals}f}{start_days['end']}"
        elif days is not None and start_text is not None:
            moved = days + shift_ms / MS_PER_DAY
            line = (
                f"{start_text['prefix']}{_trace_start_text(moved)}"
                f"{start_text['end']}"
            )
        shifted.append(line)
        if TRC_GENERATOR.match(line):
            position = len(shifted)
    shifted.insert(position, f";   {note}{ending}")
    return shifted


def _write_trc(timeline, start, stop, stream):
    with timeline.path.open("r", encoding="ascii", newline="") as source:
        lines = list(source)
    header = []
    records = []
    first = last = None
    in_records = False
    for line in lines:
        match = TRC_RECORD.match(line)
        if match is None:
            if not in_records:
                header.append(line)
            continue
        in_records = True
        offset = Decimal(match["offset"].strip())
        time = float(offset) / 1000.0
        if time < start:
            continue
        if time > stop:
            break
        if first is None:
            first = offset
        last = offset
        shifted = offset - first
        records.append(
            f"{len(records) + 1:>{len(match['number'])}})"
            f"{shifted:>{len(match['offset'])}}{match['rest']}"
        )
    if not records:
        return 0, 0.0
    name = timeline.path.name.encode("ascii", "replace").decode("ascii")
    note = f"Excerpt of {name}: source offsets {first}..{last} ms"
    stream.write("".join(_shift_trace_header(header, first, note)))
    stream.write("".join(records))
    return len(records), float(last - first) / 1000.0


def _write_candump(timeline, start, stop, stream):
    kept = 0
    first = None
    last = 0.0
    first_kept = last_kept = None
    with timeline.path.open("r", encoding="utf-8", newline="") as source:
        for line in source:
            parsed = can_telemetry.parse_candump_line(line)
            if parsed is None:
                continue
            timestamp = parsed[2]
            if timestamp is not None:
                if first is None:
                    first = timestamp
                last = max(last, timestamp - first)
            if last < start:
                continue
            if last > stop:
                break
            if first_kept is None:
                first_kept = last
            last_kept = last
            stream.write(line)
            kept += 1
    if not kept:
        return 0, 0.0
    return kept, last_kept - first_kept


def _write_mlg(timeline, start, stop, stream):
    path = timeline.path
    mlvlg.validate_mlg(path)
    fields = mlvlg.read_fields(path)
    offsets = {}
    position = 0
    for field in fields:
        offsets.setdefault(field.name, (position, field))
        position += field.data_size
    if "Elapsed" not in offsets or offsets["Elapsed"][1].field_type != mlvlg.MLG_F32:
        raise ExcerptError(f"{path.name} has no F32 Elapsed channel")
    elapsed_offset = offsets["Elapsed"][0]
    time_bytes = [
        (offsets[name][0], offsets[name][0] + offsets[name][1].data_size)
        for name in TIME_FIELDS
        if name in offsets
    ]

    def without_time(payload):
        value = bytearray(payload)
        for low, high in time_bytes:
            value[low:high] = bytes(high - low)
        return bytes(value)

    data = path.read_bytes()
    header = MLG_HEADER.unpack_from(data)
    start_timestamp, data_begin, record_length = header[2], header[4], header[5]
    blocks = []
    previous = None
    last_time = None
    first = last = None
    offset = data_begin
    while offset < len(data):
        if data[offset] != 0:
            # A marker block carries no elapsed time of its own.
            offset += 4 + mlvlg.MLG_MARKER_MESSAGE_SIZE
            continue
        payload = data[offset + 4:offset + 4 + record_length]
        offset += 4 + record_length + 1
        time = float(struct.unpack_from(">f", payload, elapsed_offset)[0])
        if last_time is not None and time < last_time:
            time = last_time
        last_time = time
        masked = without_time(payload)
        bridge = masked == previous
        previous = masked
        if time < start or (bridge and first is None):
            continue
        if time > stop:
            break
        if first is None:
            first = time
        last = time
        moved = bytearray(payload)
        struct.pack_into(">f", moved, elapsed_offset, time - first)
        blocks.append(
            mlvlg.encode_payload_block(bytes(moved), len(blocks), time - first)
        )
    if not blocks:
        return 0, 0.0
    moved_header = bytearray(data[:data_begin])
    struct.pack_into(
        ">I",
        moved_header,
        MLG_TIMESTAMP_OFFSET,
        start_timestamp + math.floor(first),
    )
    stream.write(bytes(moved_header))
    stream.write(b"".join(blocks))
    return len(blocks), last - first


def _validate(kind, path):
    if kind == "TRC":
        peak_trc_audit.load_trace(path)
    elif kind == "MLG":
        mlvlg.validate_mlg(path)


def save_excerpt(timeline, start, stop, output, force=False):
    """Write the records of the replay time region start..stop to output.

    The output keeps the format of the timeline source and is replaced only
    with force; a failed excerpt leaves no file behind.
    """
    output = Path(output)
    source = timeline.path
    if output.resolve() == source.resolve():
        raise ExcerptError("an excerpt cannot replace its source")
    if _reader_kind(output) != timeline.kind:
        raise ExcerptError(
            f"{output.name} would not be read as {timeline.kind}; "
            f"keep the {source.suffix} suffix"
        )
    if output.exists() and not force:
        raise ExcerptError(f"{output.name} already exists")
    writers = {"TRC": _write_trc, "candump": _write_candump, "MLG": _write_mlg}
    binary = timeline.kind == "MLG"
    output.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{output.name}.",
        suffix=".tmp",
        dir=output.parent,
    )
    temporary = Path(temporary_name)
    try:
        if binary:
            stream = os.fdopen(descriptor, "wb")
        else:
            encoding = "ascii" if timeline.kind == "TRC" else "utf-8"
            stream = os.fdopen(descriptor, "w", encoding=encoding, newline="")
        with stream:
            records, duration = writers[timeline.kind](
                timeline, start, stop, stream
            )
        if not records:
            raise ExcerptError("the region holds no records")
        _validate(timeline.kind, temporary)
        os.replace(temporary, output)
    except (
        OSError,
        UnicodeError,
        struct.error,
        peak_trc_audit.TraceError,
        mlvlg.MlvlgError,
    ) as error:
        temporary.unlink(missing_ok=True)
        raise ExcerptError(str(error)) from error
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise
    return Excerpt(output, records, duration)
