#!/usr/bin/env python3
"""Audit PEAK PCAN-View TRC 1.1 classical-CAN captures."""

from __future__ import annotations

import argparse
from collections import defaultdict
from dataclasses import asdict, dataclass
import json
from pathlib import Path
import re
import statistics


FRAME_RE = re.compile(
    r"^\s*(?P<number>\d+)\)\s+"
    r"(?P<offset_ms>\d+(?:\.\d+)?)\s+"
    r"(?P<direction>Rx|Tx)\s+"
    r"(?P<can_id>(?:[0-9A-Fa-f]{4}|[0-9A-Fa-f]{8}))\s+"
    r"(?P<dlc>\d+)"
    r"(?P<data>(?:\s+[0-9A-Fa-f]{2})*)\s*$"
)
RTR_RE = re.compile(
    r"^\s*(?P<number>\d+)\)\s+"
    r"(?P<offset_ms>\d+(?:\.\d+)?)\s+"
    r"(?P<direction>Rx|Tx)\s+"
    r"(?P<can_id>(?:[0-9A-Fa-f]{4}|[0-9A-Fa-f]{8}))\s+"
    r"(?P<dlc>\d+)\s+RTR\s*$"
)
STATUS_RE = re.compile(
    r"^\s*(?P<number>\d+)\)\s+"
    r"(?P<offset_ms>\d+(?:\.\d+)?)\s+"
    r"(?P<kind>Warng|Error)\s+"
    r"(?P<code>[0-9A-Fa-f]{4,8})\s+"
    r"(?P<dlc>\d+)"
    r"(?P<data>(?:\s+[0-9A-Fa-f]{2})*)"
    r"(?:\s+(?P<description>\S.*))?\s*$"
)
HEADER_RE = re.compile(r"^;\$(?P<key>[A-Z]+)=(?P<value>.*)$")
START_RE = re.compile(r"^;\s*Start time:\s*(?P<value>.*)$")
GENERATOR_RE = re.compile(r"^;\s*Generated by\s+(?P<value>.*)$")

KNOWN_JK08A_ECM_IDS = (
    0x160,
    0x180,
    0x182,
    0x1F9,
    0x239,
    0x512,
    0x551,
    0x580,
    0x6E2,
)


class TraceError(ValueError):
    """Raised when a trace is malformed or outside the supported contract."""


@dataclass(frozen=True)
class Frame:
    number: int
    offset_ms: float
    direction: str
    can_id: int
    data: bytes
    is_extended: bool = False
    remote: bool = False
    declared_dlc: int | None = None

    @property
    def dlc(self):
        return len(self.data) if self.declared_dlc is None else self.declared_dlc

    @property
    def extended(self):
        return self.is_extended


@dataclass(frozen=True)
class StatusRecord:
    number: int
    offset_ms: float
    kind: str
    code: int
    data: bytes
    description: str | None


@dataclass(frozen=True)
class Trace:
    path: Path
    file_version: str
    start_time: str | None
    start_description: str | None
    generator: str | None
    frames: tuple[Frame, ...]
    status_records: tuple[StatusRecord, ...]


@dataclass(frozen=True)
class IdentifierAudit:
    can_id: int
    extended: bool
    count: int
    dlcs: tuple[int, ...]
    first_ms: float
    last_ms: float
    median_period_ms: float | None
    p95_period_ms: float | None
    p99_period_ms: float | None
    maximum_period_ms: float | None
    unique_payloads: int
    remote_count: int


@dataclass(frozen=True)
class LoadAudit:
    bitrate: int
    average_min_percent: float
    average_max_percent: float
    peak_100ms_min_percent: float
    peak_100ms_max_percent: float
    peak_1000ms_min_percent: float
    peak_1000ms_max_percent: float


@dataclass(frozen=True)
class TraceAudit:
    path: str
    file_version: str
    start_time: str | None
    start_description: str | None
    generator: str | None
    first_offset_ms: float
    last_offset_ms: float
    duration_ms: float
    frame_count: int
    remote_count: int
    warning_count: int
    error_count: int
    rx_count: int
    tx_count: int
    standard_id_count: int
    extended_id_count: int
    candidate_id: int
    candidate_count: int
    load: LoadAudit | None
    identifiers: tuple[IdentifierAudit, ...]


def load_trace(path):
    path = Path(path)
    try:
        lines = path.read_text(encoding="ascii").splitlines()
    except (OSError, UnicodeError) as error:
        raise TraceError(f"cannot read {path}: {error}") from error

    headers = {}
    start_description = None
    generator = None
    frames = []
    status_records = []
    record_order = []
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        header = HEADER_RE.match(line)
        if header:
            headers[header.group("key")] = header.group("value").strip()
            continue
        start = START_RE.match(line)
        if start:
            start_description = start.group("value").strip()
            continue
        generated = GENERATOR_RE.match(line)
        if generated:
            generator = generated.group("value").strip()
            continue
        if line.startswith(";"):
            continue
        match = FRAME_RE.match(line)
        remote = False
        if match is None:
            match = RTR_RE.match(line)
            remote = match is not None
        if match is None:
            status = STATUS_RE.match(line)
            if status is not None:
                dlc = int(status.group("dlc"))
                data = bytes.fromhex(status.group("data").strip())
                if dlc != 4 or len(data) != 4:
                    raise TraceError(
                        f"{path}:{line_number}: {status.group('kind')} row "
                        "must contain four status bytes"
                    )
                record = StatusRecord(
                    number=int(status.group("number")),
                    offset_ms=float(status.group("offset_ms")),
                    kind=status.group("kind"),
                    code=int(status.group("code"), 16),
                    data=data,
                    description=status.group("description"),
                )
                status_records.append(record)
                record_order.append((record.number, record.offset_ms))
                continue
            raise TraceError(f"{path}:{line_number}: unsupported TRC row")
        dlc = int(match.group("dlc"))
        if not 0 <= dlc <= 8:
            raise TraceError(f"{path}:{line_number}: invalid classical-CAN DLC")
        data_text = "" if remote else match.group("data").strip()
        data = bytes.fromhex(data_text) if data_text else b""
        if not remote and len(data) != dlc:
            raise TraceError(
                f"{path}:{line_number}: row declares DLC {dlc} but has "
                f"{len(data)} data bytes"
            )
        can_id_text = match.group("can_id")
        can_id = int(can_id_text, 16)
        extended = len(can_id_text) == 8
        maximum_id = 0x1FFFFFFF if extended else 0x7FF
        if not 0 <= can_id <= maximum_id:
            raise TraceError(f"{path}:{line_number}: CAN ID is out of range")
        frame = Frame(
            number=int(match.group("number")),
            offset_ms=float(match.group("offset_ms")),
            direction=match.group("direction"),
            can_id=can_id,
            data=data,
            is_extended=extended,
            remote=remote,
            declared_dlc=dlc,
        )
        frames.append(frame)
        record_order.append((frame.number, frame.offset_ms))

    if headers.get("FILEVERSION") != "1.1":
        raise TraceError(
            f"{path}: expected PEAK TRC file version 1.1, got "
            f"{headers.get('FILEVERSION')!r}"
        )
    if not frames:
        raise TraceError(f"{path}: trace contains no supported CAN frames")
    for expected, (number, _) in enumerate(record_order, start=1):
        if number != expected:
            raise TraceError(
                f"{path}: message number {number} follows "
                f"{expected - 1}"
            )
    for left, right in zip(record_order, record_order[1:]):
        if right[1] < left[1]:
            raise TraceError(
                f"{path}: timestamp decreases at message {right[0]}"
            )
    return Trace(
        path=path,
        file_version=headers["FILEVERSION"],
        start_time=headers.get("STARTTIME"),
        start_description=start_description,
        generator=generator,
        frames=tuple(frames),
        status_records=tuple(status_records),
    )


def frame_bit_bounds(frame):
    """Return unstuffed and conservative maximum-stuffed frame lengths."""
    payload_bits = 0 if frame.remote else 8 * frame.dlc
    if frame.extended:
        base = 67 + payload_bits
        stuffable = 54 + payload_bits
    else:
        base = 47 + payload_bits
        stuffable = 34 + payload_bits
    return base, base + (stuffable - 1) // 4


def percentile(values, fraction):
    if not values:
        return None
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    weight = position - lower
    return ordered[lower] * (1 - weight) + ordered[upper] * weight


def _identifier_audits(frames):
    grouped = defaultdict(list)
    for frame in frames:
        grouped[(frame.extended, frame.can_id)].append(frame)
    result = []
    for (extended, can_id), items in sorted(grouped.items()):
        periods = [
            right.offset_ms - left.offset_ms
            for left, right in zip(items, items[1:])
        ]
        result.append(IdentifierAudit(
            can_id=can_id,
            extended=extended,
            count=len(items),
            dlcs=tuple(sorted({item.dlc for item in items})),
            first_ms=items[0].offset_ms,
            last_ms=items[-1].offset_ms,
            median_period_ms=(statistics.median(periods) if periods else None),
            p95_period_ms=percentile(periods, 0.95),
            p99_period_ms=percentile(periods, 0.99),
            maximum_period_ms=max(periods) if periods else None,
            unique_payloads=len({(item.remote, item.data) for item in items}),
            remote_count=sum(item.remote for item in items),
        ))
    return tuple(result)


def _peak_window_bits(frames, window_ms, select):
    left = 0
    current = 0
    maximum = 0
    for right, frame in enumerate(frames):
        current += select(frame_bit_bounds(frame))
        while frame.offset_ms - frames[left].offset_ms >= window_ms:
            current -= select(frame_bit_bounds(frames[left]))
            left += 1
        maximum = max(maximum, current)
    return maximum


def _load_audit(frames, duration_ms, bitrate):
    if type(bitrate) is not int or bitrate <= 0:
        raise TraceError("bitrate must be a positive integer")
    if duration_ms <= 0:
        raise TraceError("trace duration must be positive")
    minimum_bits = sum(frame_bit_bounds(frame)[0] for frame in frames)
    maximum_bits = sum(frame_bit_bounds(frame)[1] for frame in frames)
    capacity = bitrate * duration_ms / 1000

    def percent(bits, window_ms):
        return 100 * bits / (bitrate * window_ms / 1000)

    return LoadAudit(
        bitrate=bitrate,
        average_min_percent=100 * minimum_bits / capacity,
        average_max_percent=100 * maximum_bits / capacity,
        peak_100ms_min_percent=percent(
            _peak_window_bits(frames, 100, lambda pair: pair[0]), 100
        ),
        peak_100ms_max_percent=percent(
            _peak_window_bits(frames, 100, lambda pair: pair[1]), 100
        ),
        peak_1000ms_min_percent=percent(
            _peak_window_bits(frames, 1000, lambda pair: pair[0]), 1000
        ),
        peak_1000ms_max_percent=percent(
            _peak_window_bits(frames, 1000, lambda pair: pair[1]), 1000
        ),
    )


def audit_trace(trace, *, candidate_id=0x6F0, bitrate=None):
    if not 0 <= candidate_id <= 0x1FFFFFFF:
        raise TraceError("candidate CAN ID is out of range")
    offsets = [frame.offset_ms for frame in trace.frames]
    offsets.extend(record.offset_ms for record in trace.status_records)
    first = min(offsets)
    last = max(offsets)
    duration = last - first
    identifiers = _identifier_audits(trace.frames)
    standard = {item.can_id for item in identifiers if not item.extended}
    extended = {item.can_id for item in identifiers if item.extended}
    return TraceAudit(
        path=str(trace.path),
        file_version=trace.file_version,
        start_time=trace.start_time,
        start_description=trace.start_description,
        generator=trace.generator,
        first_offset_ms=first,
        last_offset_ms=last,
        duration_ms=duration,
        frame_count=len(trace.frames),
        remote_count=sum(frame.remote for frame in trace.frames),
        warning_count=sum(
            record.kind == "Warng" for record in trace.status_records
        ),
        error_count=sum(
            record.kind == "Error" for record in trace.status_records
        ),
        rx_count=sum(frame.direction == "Rx" for frame in trace.frames),
        tx_count=sum(frame.direction == "Tx" for frame in trace.frames),
        standard_id_count=len(standard),
        extended_id_count=len(extended),
        candidate_id=candidate_id,
        candidate_count=sum(
            frame.can_id == candidate_id and not frame.extended
            for frame in trace.frames
        ),
        load=(
            _load_audit(trace.frames, duration, bitrate)
            if bitrate is not None
            else None
        ),
        identifiers=identifiers,
    )


def _format_period(value):
    return "-" if value is None else f"{value:.3f}"


def format_audit(audit, *, all_ids=False):
    lines = [
        f"TRACE path={audit.path}",
        (
            f"format={audit.file_version} start={audit.start_description!r} "
            f"frames={audit.frame_count} rx={audit.rx_count} tx={audit.tx_count} "
            f"rtr={audit.remote_count} warnings={audit.warning_count} "
            f"errors={audit.error_count} "
            f"duration_s={audit.duration_ms / 1000:.3f} "
            f"standard_ids={audit.standard_id_count} "
            f"extended_ids={audit.extended_id_count}"
        ),
        (
            f"candidate_id=0x{audit.candidate_id:X} "
            f"candidate_count={audit.candidate_count}"
        ),
    ]
    if audit.load is None:
        lines.append("bus_load=not_calculated bitrate=not_recorded_by_trc")
    else:
        load = audit.load
        lines.append(
            f"bus_load bitrate={load.bitrate} "
            f"average={load.average_min_percent:.3f}.."
            f"{load.average_max_percent:.3f}% "
            f"peak_100ms={load.peak_100ms_min_percent:.3f}.."
            f"{load.peak_100ms_max_percent:.3f}% "
            f"peak_1000ms={load.peak_1000ms_min_percent:.3f}.."
            f"{load.peak_1000ms_max_percent:.3f}%"
        )
    selected = audit.identifiers if all_ids else tuple(
        item for item in audit.identifiers
        if not item.extended and item.can_id in KNOWN_JK08A_ECM_IDS
    )
    lines.append(
        "ID         COUNT DLC RTR PERIOD_MED_MS P95_MS  P99_MS  MAX_MS  UNIQUE"
    )
    for item in selected:
        identifier = (
            f"0x{item.can_id:08X}" if item.extended
            else f"0x{item.can_id:03X}"
        )
        lines.append(
            f"{identifier:>10s} {item.count:7d} "
            f"{','.join(str(value) for value in item.dlcs):>3s} "
            f"{item.remote_count:3d} "
            f"{_format_period(item.median_period_ms):>13s} "
            f"{_format_period(item.p95_period_ms):>7s} "
            f"{_format_period(item.p99_period_ms):>7s} "
            f"{_format_period(item.maximum_period_ms):>7s} "
            f"{item.unique_payloads:7d}"
        )
    return "\n".join(lines)


def _json_data(audit):
    return asdict(audit)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("traces", nargs="+", type=Path)
    parser.add_argument(
        "--candidate-id", type=lambda value: int(value, 0), default=0x6F0
    )
    parser.add_argument(
        "--bitrate",
        type=int,
        help="explicit nominal bitrate; TRC 1.1 does not store it",
    )
    parser.add_argument(
        "--all-ids", action="store_true", help="print every observed CAN ID"
    )
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        audits = [
            audit_trace(
                load_trace(path),
                candidate_id=args.candidate_id,
                bitrate=args.bitrate,
            )
            for path in args.traces
        ]
    except TraceError as error:
        parser.error(str(error))
    if args.json:
        print(json.dumps([_json_data(item) for item in audits], indent=2))
    else:
        print("\n\n".join(format_audit(item, all_ids=args.all_ids) for item in audits))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
