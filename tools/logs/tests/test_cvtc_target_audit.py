class CvtcRecordingInputTest(unittest.TestCase):
    def test_mlg_recording_reproduces_the_trace_audit(self):
        ticks = (*range(1, 61), *range(1, 41))
        with tempfile.TemporaryDirectory() as directory:
            trace = Path(directory) / "cvtc.trc"
            recording = Path(directory) / "cvtc.mlg"
            write_cvtc_trace(trace, ticks, gap_after=30)
            conversion = trc_to_mlg.convert_trace(trace, recording)
            self.assertTrue(cvtc_target_audit.is_mlg(recording))
            self.assertFalse(cvtc_target_audit.is_mlg(trace))
            results = {}
            for target in ("intake", "exhaust"):
                from_trace = cvtc_target_audit.audit_trace(trace, target=target)
                from_recording = cvtc_target_audit.audit_trace(
                    recording, target=target
                )
                results[target] = from_recording
                for field in dataclasses.fields(from_trace):
                    if field.name in SOURCE_ONLY_FIELDS:
                        continue
                    self.assertEqual(
                        getattr(from_recording, field.name),
                        getattr(from_trace, field.name),
                        f"{target} {field.name}",
                    )
            _events, _bridges, samples = cvtc_target_audit._recording_samples(
                mlg_relation_audit.read_recording(recording), "tuning"
            )
            report = io.StringIO()
            with contextlib.redirect_stdout(report):
                cvtc_target_audit.main(["--source-lags", "1", str(recording)])

        intake = results["intake"]
        self.assertEqual(intake.source_format, "mlg")
        self.assertIsNone(intake.source_frames)
        self.assertIsNone(intake.coolant_age_max_ms)
        self.assertGreater(conversion.bridge_records, 0)
        self.assertEqual(intake.bridge_records, conversion.bridge_records)
        self.assertEqual(
            intake.source_records,
            conversion.mlg_records + conversion.bridge_records,
        )
        self.assertEqual(intake.complete_snapshots, conversion.complete_snapshots)
        self.assertEqual({sample.run for sample in samples}, {0, 1})
        lag_1 = intake.alignments[1]
        self.assertEqual(
            {band for band, _count in lag_1.coolant_band_counts},
            {"cold", "blend", "warm"},
        )
        self.assertGreater(lag_1.correction_active_count, 0)
        self.assertIsNotNone(lag_1.alternate_source_to_reference)
        exhaust_lag_1 = results["exhaust"].alignments[1]
        self.assertIsNone(exhaust_lag_1.alternate_source_to_reference)
        text = report.getvalue()
        self.assertIn(
            f"records={intake.source_records}, "
            f"bridge={intake.bridge_records}, ",
            text,
        )
        self.assertIn("retained_context_max_age=n/a", text)
        self.assertIn("alternate_ffff1553_to_reference_a: exact=", text)
        self.assertIn("alternate_ffff1553_active_to_active: ", text)
        self.assertIn("cold_dependent_active_to_active: ", text)

