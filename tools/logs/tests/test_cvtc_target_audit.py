    def test_alignment_filters_bands_and_compares_the_alternate_source(self):
        def sample(tick, reference):
            return cvtc_target_audit.CvtcSample(
                timestamp=tick / 100.0,
                run=0,
                tick=tick,
                bfs_raw=1,
                rpm_raw=4,
                coolant_raw=100,
                coolant_age_ms=math.nan,
                knock_surface_state=0,
                reference_a_raw=reference,
                reference_b_raw=128,
                intake_actual_b1_raw=128,
                intake_actual_b2_raw=128,
            )

        def point(band, selected, alternate):
            return cvtc_target_audit.ReplayPoint(
                load_raw=1,
                rpm50_raw=1,
                cold_raw=selected,
                main_base_raw=selected,
                correction_raw=128,
                main_selected_raw=selected,
                coolant_selected_raw=selected,
                coolant_band=band,
                correction_active=False,
                alternate_source_raw=alternate,
            )

        samples = [sample(tick, reference) for tick, reference in enumerate(
            (168, 168, 128, 128, 160, 150)
        )]
        points = [
            point("cold", 148, 168),
            point("cold", 148, 168),
            point("cold", 148, 128),
            point("cold", 148, 158),
            point("blend", 160, 128),
            point("warm", 150, 128),
        ]
        cold = cvtc_target_audit._alignment_summary(
            samples, points, 0, 1, (), coolant_bands=("cold",)
        )
        self.assertEqual(cold.comparisons, 4)
        self.assertEqual(cold.coolant_band_counts, (("cold", 4),))
        self.assertEqual(cold.selected_to_reference_a.exact, 0)
        self.assertEqual(cold.alternate_source_to_reference.exact, 3)
        self.assertEqual(cold.alternate_source_to_reference.comparisons, 4)
        self.assertEqual(cold.alternate_source_active_to_active.exact, 2)
        self.assertEqual(cold.alternate_source_active_to_active.comparisons, 2)
        every_band = cvtc_target_audit._alignment_summary(
            samples, points, 0, 1, ()
        )
        self.assertEqual(every_band.selected_to_reference_a.exact, 2)
        self.assertEqual(every_band.alternate_source_to_reference.exact, 3)
        self.assertEqual(
            every_band.alternate_source_active_to_active.comparisons, 2
        )
        with self.assertRaisesRegex(ValueError, "coolant bands warm"):
            cvtc_target_audit._alignment_summary(
                samples[:2], points[:2], 0, 1, (), coolant_bands=("warm",)
            )


