    def test_intake_alternate_target_weights_the_centered_speed_lookup(self):
        source = cvtc_target_audit.IntakeAlternateSource(
            speed_axis=(16, 20, 24, 28, 32, 36, 40, 44),
            speed_table=(128, 128, 128, 148, 168, 168, 168, 127),
            coolant_weight=(0, 0, 0, 0, 0, 0, 128, 128, 128, 0, 0, 0, 0, 0, 64, 1),
        )
        target = cvtc_target_audit.intake_alternate_target
        self.assertEqual(target(source, 35, 80), 168)
        self.assertEqual(target(source, 30, 80), 158)
        self.assertEqual(target(source, 35, 91), 165)
        self.assertEqual(target(source, 35, 140), 128)
        # A negative product divides toward zero, as the +127 bias before the
        # arithmetic shift at 0xBDBB4 does.
        self.assertEqual(target(source, 60, 150), 128)
        self.assertEqual(target(source, 60, 170), 128)
        saturating = cvtc_target_audit.IntakeAlternateSource(
            speed_axis=(0, 128),
            speed_table=(0, 255),
            coolant_weight=(255,) * 16,
        )
        self.assertEqual(target(saturating, 0, 140), 0)
        self.assertEqual(target(saturating, 128, 140), 255)

